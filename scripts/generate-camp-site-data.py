#!/usr/bin/env python3
"""Export exact camp chest and selected-template identities from one ao-bin-dumps revision.

Needs lootchests.xml, dynamictemplates.xml and miststemplatemetadata.xml.
"""
from pathlib import Path
import sys
import xml.etree.ElementTree as ET


def main(source):
    source = Path(source)
    chests = []
    for chest in ET.parse(source / 'lootchests.xml').getroot():
        states = chest.findall('RareStates/RareState')
        # Only the explicit camp definitions whose standard state is a fame-book reward.
        if chest.get('chesttype', '').endswith(('mistscamp', 'dynamiccamp')) and any(
                s.get('state') == 'standard' and s.get('namelocatag', '').endswith('_FAME') for s in states):
            chests.append(chest.get('uniquename'))
    sites = {}
    for group in ET.parse(source / 'dynamictemplates.xml').getroot().iter('type'):
        category = group.get('category', '')
        kind = 'CampSite' if category == 'mobcamp' else 'ResourceSite' if category == 'resource' or category.startswith('critter_') else 'OtherSite'
        for template in group.findall('template'):
            name = template.get('id')
            if name in sites and sites[name] != kind:
                raise ValueError(f'Ambiguous template: {name}')
            sites[name] = kind
    for template in ET.parse(source / 'miststemplatemetadata.xml').getroot().findall('template'):
        name = template.get('name')
        sites[name] = 'CampSite' if '_PVE_' in name else 'ResourceSite' if '_RES_' in name else 'OtherSite'
    lines = ['// <auto-generated>', '// Written by scripts/generate-camp-site-data.py from ao-bin-dumps; rerun rather than editing.',
             '// </auto-generated>', 'using AlbionDataAvalonia.Activity.Models;', 'using System;', 'using System.Collections.Generic;',
             '', 'namespace AlbionDataAvalonia.Activity;', '', 'internal static partial class ActivityCampSites', '{',
             '    internal static readonly HashSet<string> CampChests = new(StringComparer.OrdinalIgnoreCase)', '    {']
    lines += [f'        "{name}",' for name in sorted(chests)]
    lines += ['    };', '', '    internal static readonly Dictionary<string, ActivityLiveActorKind> Templates = new(StringComparer.OrdinalIgnoreCase)', '    {']
    lines += [f'        ["{name}"] = ActivityLiveActorKind.{kind},' for name, kind in sorted(sites.items())]
    lines += ['    };', '}', '']
    target = Path(__file__).resolve().parent.parent / 'AlbionDataAvalonia/Activity/ActivityCampSiteCatalog.g.cs'
    target.write_text('\n'.join(lines))
    print(f'Exported {len(chests)} camp chest identities and {len(sites)} selected templates')


if __name__ == '__main__':
    main(sys.argv[1])
