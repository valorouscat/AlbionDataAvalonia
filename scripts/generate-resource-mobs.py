#!/usr/bin/env python3
"""Writes AlbionDataAvalonia/Activity/ActivityResourceMobCatalog.g.cs from the game's mobs.json.

The live map shows the mobs that yield gathering resources when killed or harvested. mobs.json (from
https://github.com/ao-data/ao-bin-dumps) lists each mob's Harvestable loot; its type names the resource:
HIDE, FIBER_CRITTER, ORE_GUARDIAN_ROADS and so on. Rerun after a game patch adds mobs:

    curl -sSLo /tmp/mobs.json https://raw.githubusercontent.com/ao-data/ao-bin-dumps/master/mobs.json
    python3 scripts/generate-resource-mobs.py /tmp/mobs.json
"""
import json
import re
import sys
from pathlib import Path

FAMILIES = {"HIDE": "Hide", "FIBER": "Fiber", "WOOD": "Wood", "ORE": "Ore", "ROCK": "Stone"}


def harvestables(value):
    if isinstance(value, dict):
        for key, inner in value.items():
            if key == "Harvestable":
                yield from inner if isinstance(inner, list) else [inner]
            else:
                yield from harvestables(inner)
    elif isinstance(value, list):
        for inner in value:
            yield from harvestables(inner)


def main(source: str) -> None:
    mobs = json.loads(Path(source).read_text(encoding="utf-8"))["Mobs"]["Mob"]
    found = {}
    for mob in mobs:
        name = mob.get("@uniquename", "")
        if not re.match(r"^T[1-8]_", name):
            continue
        for harvestable in harvestables(mob.get("Loot", {})):
            family = FAMILIES.get(str(harvestable.get("@type", "")).split("_")[0])
            if family:
                found[name] = family
    lines = [
        "// <auto-generated>",
        "// Written by scripts/generate-resource-mobs.py from the game's mobs.json; rerun it rather than editing.",
        "// </auto-generated>",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace AlbionDataAvalonia.Activity;",
        "",
        "internal static partial class ActivityResourceMobs",
        "{",
        "    private static readonly Dictionary<string, string> Catalog = new(StringComparer.OrdinalIgnoreCase)",
        "    {",
    ]
    lines += [f'        ["{name}"] = "{family}",' for name, family in sorted(found.items())]
    lines += ["    };", "}", ""]
    target = Path(__file__).resolve().parent.parent / "AlbionDataAvalonia" / "Activity" / "ActivityResourceMobCatalog.g.cs"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(found)} resource mobs to {target}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "mobs.json")
