#!/usr/bin/env python3
"""Export possible Abbey POIs from an ao-bin-dumps checkout at one pinned revision.

Needs templates/GREEN/MISTS_DNG_UND_01.template.xml, cluster/tiles.xml,
miststemplatemetadata.xml and mists.xml from the same revision.
Room layers are alternatives selected at runtime: output is a union of possible spots.
Expand compound transforms/active layers, but never imply all candidates are present.
"""
import sys
import json
import xml.etree.ElementTree as ET
from pathlib import Path
from template_geometry import IDENTITY, walk

ROOT = Path(__file__).resolve().parent.parent
MASTER = 'MISTS_DNG_UND_01'


def main(source):
    source = Path(source)
    catalog = ET.parse(source/'cluster/tiles.xml').getroot()
    compounds = {x.get('name'): x for x in catalog.findall('compoundtile')}
    template = ET.parse(source/f'templates/GREEN/{MASTER}.template.xml').getroot()
    dungeon = ET.parse(source/'miststemplatemetadata.xml').getroot().find(f"dungeon[@name='{MASTER}']")
    if dungeon is None:
        raise ValueError(f'Missing room metadata for {MASTER}')
    rooms = {layer.get('id'): room.get('idx') for room in dungeon.findall('room') for layer in room.findall('layer')}
    modes = ET.parse(source/'mists.xml').getroot().findall("mistsmodes/mistsmode[@type='mistsdungeon']")
    rules = {(mode.get('numberofbossrooms'), mode.get('bossroompreventionradius')) for mode in modes}
    if len(rules) != 1 or any(value is None for value in next(iter(rules))):
        raise ValueError('Expected one explicit boss-room count/radius rule across Abbey modes')
    boss_count, prevention_radius = next(iter(rules))
    # Keep layer identity: the union alone hides regular-room minibosses among boss alternatives.
    spawn_notes = {}
    for layer in template.iter('layer'):
        layer_id = layer.get('id', '')
        for name, matrix in walk(layer, IDENTITY, compounds):
            if not (name == 'SpawnPoint_RANDOM_MD_UNDEAD_ANY_BOSS' or
                    name == 'SpawnPoint_LOOTCHEST_MD_UNDEAD_SOLO_BOSS' or
                    name.startswith('SpawnPoint_RANDOM_MD_UNDEAD_') and name.endswith('_MINIBOSS')):
                continue
            room = rooms.get(layer_id)
            if room is None:
                raise ValueError(f'Spawn layer missing from room metadata: {layer_id}')
            if layer_id.endswith('_BOSS'):
                notes = [f'Room {room}: boss-room variant',
                         f'{boss_count} boss rooms per instance; boss-room prevention radius {prevention_radius} m',
                         'A candidate position, not a guaranteed boss room or a measured spawn probability']
            elif layer_id.endswith('_MOBS') and name.endswith('_MINIBOSS'):
                notes = [f'Room {room}: fixed miniboss position in the regular mob layer',
                         'Replaced by the boss-room variant if this room is selected as a boss room',
                         'A template spawn position, not a guaranteed living mob; it may already be cleared']
            else:
                raise ValueError(f'Unexpected Abbey spawn layer: {layer_id}')
            spawn_notes[(name, round(matrix[4], 2)+0., round(matrix[5], 2)+0.)] = tuple(notes)
    found = set()
    for name, matrix in walk(template, IDENTITY, compounds):
        kind = label = None
        grade = 1
        if name == 'SpawnPoint_RANDOM_MD_UNDEAD_ANY_BOSS':
            kind, label, grade = 'Boss', 'Possible boss spawn', 3
        elif name.startswith('SpawnPoint_RANDOM_MD_UNDEAD_') and name.endswith('_MINIBOSS'):
            kind, label, grade = 'Miniboss', 'Regular-room miniboss spawn', 2
        elif name == 'SpawnPoint_LOOTCHEST_MD_UNDEAD_SOLO_BOSS':
            kind, label, grade = 'Chest', 'Possible boss-room chest', 3
        elif name == 'TreasureSpawnpointLootchest':
            kind, label, grade = 'Chest', 'Possible treasure chest', 2
        elif name == 'TreasureSpawnpointCoffer':
            kind, label = 'Coffer', 'Possible coffer'
        elif name == 'MISTS_GREEN_WISP_SPAWN_TREE':
            kind, label = 'Wisp', 'Wisp tree'
        elif name == 'MISTS_GREEN_HIDEOUT_EXIT_LEVER_A':
            kind, label = 'Lever', 'Lever'
        if kind:
            x, y = round(matrix[4], 2)+0., round(matrix[5], 2)+0.
            notes = spawn_notes.get((name, x, y),
                                    ('A possible template position; availability depends on the room or instance',))
            found.add((kind, label, grade, x, y, notes))
    lines = ['// <auto-generated>', '// Written by scripts/generate-abbey-pois.py; rerun instead of editing.',
             '// </auto-generated>', 'using System;', 'using System.Collections.Generic;', '',
             'namespace AlbionDataAvalonia.Maps;', '', 'internal static partial class MistsMapData', '{',
             '    private static readonly Dictionary<string, MapPoi[]> AbbeyPoints = new(StringComparer.OrdinalIgnoreCase)',
             '    {', f'        ["{MASTER}"] =', '        [']
    for kind, label, grade, x, y, notes in sorted(found):
        note_text = ', '.join(json.dumps(note) for note in (*notes, 'Not a confirmed live object'))
        lines.append(f'            new(MapPoiKind.{kind}, "{label}", {grade}, new({x:g}, {y:g}), Notes: [{note_text}]),')
    lines += ['        ],', '    };', '}', '']
    (ROOT/'AlbionDataAvalonia/Maps/AbbeyPoiData.g.cs').write_text('\n'.join(lines))
    from collections import Counter
    print('Exported', len(found), 'possible Abbey POIs:', dict(Counter(x[1] for x in found)))


if __name__ == '__main__':
    main(sys.argv[1])
