#!/usr/bin/env python3
"""Export possible Abbey POIs from an ao-bin-dumps checkout at one pinned revision.

Needs templates/GREEN/MISTS_DNG_UND_01.template.xml and cluster/tiles.xml.
Room layers are alternatives selected at runtime: output is a union of possible spots.
Expand compound transforms/active layers, but never imply all candidates are present.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from template_geometry import IDENTITY, walk

ROOT = Path(__file__).resolve().parent.parent
MASTER = 'MISTS_DNG_UND_01'


def main(source):
    source = Path(source)
    catalog = ET.parse(source/'cluster/tiles.xml').getroot()
    compounds = {x.get('name'): x for x in catalog.findall('compoundtile')}
    template = ET.parse(source/f'templates/GREEN/{MASTER}.template.xml').getroot()
    found = set()
    for name, matrix in walk(template, IDENTITY, compounds):
        kind = label = None
        grade = 1
        if name == 'SpawnPoint_RANDOM_MD_UNDEAD_ANY_BOSS':
            kind, label, grade = 'Boss', 'Possible boss spawn', 3
        elif name.startswith('SpawnPoint_RANDOM_MD_UNDEAD_') and name.endswith('_MINIBOSS'):
            kind, label, grade = 'Boss', 'Possible miniboss spawn', 2
        elif name == 'SpawnPoint_LOOTCHEST_MD_UNDEAD_SOLO_BOSS':
            kind, label, grade = 'Chest', 'Room reward: boss chest or statue', 3
        elif name == 'TreasureSpawnpointLootchest':
            kind, label, grade = 'Chest', 'Possible treasure chest', 2
        elif name == 'TreasureSpawnpointCoffer':
            kind, label = 'Coffer', 'Possible coffer'
        elif name == 'MISTS_GREEN_WISP_SPAWN_TREE':
            kind, label = 'Wisp', 'Wisp tree'
        elif name == 'MISTS_GREEN_HIDEOUT_EXIT_LEVER_A':
            kind, label = 'Lever', 'Lever'
        if kind:
            found.add((kind, label, grade, round(matrix[4], 2)+0., round(matrix[5], 2)+0.))
    lines = ['// <auto-generated>', '// Written by scripts/generate-abbey-pois.py; rerun instead of editing.',
             '// </auto-generated>', 'using System;', 'using System.Collections.Generic;', '',
             'namespace AlbionDataAvalonia.Maps;', '', 'internal static partial class MistsMapData', '{',
             '    private static readonly Dictionary<string, MapPoi[]> AbbeyPoints = new(StringComparer.OrdinalIgnoreCase)',
             '    {', f'        ["{MASTER}"] =', '        [']
    for kind, label, grade, x, y in sorted(found):
        note = ('The room can contain a boss chest or a reward statue, depending on its selected variant'
                if label.startswith('Room reward') else 'A possible template position; availability depends on the room or instance')
        lines.append(f'            new(MapPoiKind.{kind}, "{label}", {grade}, new({x:g}, {y:g}), Notes: ["{note}", "Not a confirmed live object"]),')
    lines += ['        ],', '    };', '}', '']
    (ROOT/'AlbionDataAvalonia/Maps/AbbeyPoiData.g.cs').write_text('\n'.join(lines))
    from collections import Counter
    print('Exported', len(found), 'possible Abbey POIs:', dict(Counter(x[1] for x in found)))


if __name__ == '__main__':
    main(sys.argv[1])
