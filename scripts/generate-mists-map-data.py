#!/usr/bin/env python3
"""Writes AlbionDataAvalonia/Maps/MistsMapData.g.cs from the game's Mists template files.

The map supplements Mists features and keeps Abbey's fallback geometry from the game files
at https://github.com/ao-data/ao-bin-dumps (Abbey terrain is bundled separately):

- Camp slots. A Mists instance is one of a few fixed master layouts with a handful of slots, each filled with a small or
  medium section the game picks when the instance opens: a PvE camp, a resource patch, an exit or plain landscape. Only
  the camps hold a loot chest, a little off the slot's centre. miststemplatemetadata.xml lists the slots of each master;
  the camp templates give how far their chest stands from the centre.
- Mists dungeons. miststemplatemetadata.xml lists each dungeon's minimap bounds and its rooms; the dungeon's template
  places a boss chest in many rooms and the exits back to the Mists. Only the dungeons the client can recognise (those
  named in the shared core's activity-world.json) are written.

Rerun after a game patch changes the Mists:

    git clone --depth 1 --filter=blob:none --sparse https://github.com/ao-data/ao-bin-dumps.git /tmp/ao-bin-dumps
    git -C /tmp/ao-bin-dumps sparse-checkout set --no-cone /miststemplatemetadata.xml '/templates/*/MISTS_[MS]_PVE_*' \\
        '/templates/*/MISTS_DNG_*'
    python3 scripts/generate-mists-map-data.py /tmp/ao-bin-dumps
"""
import json
import math
import re
import sys
import xml.etree.ElementTree as ElementTree
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ACTIVITY_WORLD = ROOT / "shared" / "AFMDataClientCore" / "src" / "AFMDataClient.Core" / "Locations" / "activity-world.json"
CHEST = re.compile(r'name="SpawnPoint_LOOTCHEST[^"]*"\s+pos="([^"]+)"')
EXIT = re.compile(r'<(?:tile|criticaltile) name="MistsDungeonExit" pos="([^"]+)"')


def ground(pos: str) -> tuple[float, float]:
    """A template position is "x height z"; the map uses x and z."""
    x, _, z = (float(value) for value in pos.split())
    return round(x, 1), round(z, 1)


def pair(value: str) -> tuple[float, float]:
    x, z = (float(part) for part in value.split())
    return round(x, 1), round(z, 1)


def unique(values):
    return list(dict.fromkeys(values))


def chest_radius(dumps: Path, size: str) -> int:
    """The farthest any camp of this size puts its chest from its centre, rounded up to whole metres."""
    farthest = 0.0
    for template in dumps.glob(f"templates/*/MISTS_{size[0]}_PVE_*.template.xml"):
        for match in CHEST.finditer(template.read_text(encoding="utf-8")):
            farthest = max(farthest, math.hypot(*ground(match.group(1))))
    if farthest == 0:
        raise SystemExit(f"No {size.lower()} Mists camp templates with a chest under {dumps / 'templates'}")
    return math.ceil(farthest)


def dungeon_template(dumps: Path, name: str) -> Path:
    found = sorted(dumps.glob(f"templates/*/{name}.template.xml"))
    if not found:
        raise SystemExit(f"No template for Mists dungeon {name} under {dumps / 'templates'}")
    return found[0]


def number(value: float) -> str:
    return f"{value:g}"


def points(values) -> str:
    return ", ".join(f"({number(x)}, {number(z)})" for x, z in values)


def main(source: str) -> None:
    dumps = Path(source)
    metadata = ElementTree.parse(dumps / "miststemplatemetadata.xml").getroot()
    masters = {}
    for master in metadata.iter("master"):
        slots = unique(ground(slot.get("pos", "")) + (slot.get("size") == "Medium",) for slot in master.iter("slot"))
        if slots:
            masters[master.get("name")] = slots
    small, medium = chest_radius(dumps, "Small"), chest_radius(dumps, "Medium")

    known = set(json.loads(ACTIVITY_WORLD.read_text(encoding="utf-8"))["mistsLayouts"].values())
    dungeons = {}
    for dungeon in metadata.iter("dungeon"):
        name = dungeon.get("name")
        if name not in known:
            continue
        rooms = [pair(rect.get("vMin")) + pair(rect.get("vMax")) for rect in dungeon.iter("rect")]
        text = dungeon_template(dumps, name).read_text(encoding="utf-8")
        chests = unique(ground(match.group(1)) for match in CHEST.finditer(text))
        exits = unique(ground(match.group(1)) for match in EXIT.finditer(text))
        dungeons[name] = (pair(dungeon.get("minimapBoundsMin")), pair(dungeon.get("minimapBoundsMax")), rooms, chests, exits)

    lines = [
        "// <auto-generated>",
        "// Written by scripts/generate-mists-map-data.py from the game's Mists templates; rerun it rather than editing.",
        "// </auto-generated>",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace AlbionDataAvalonia.Maps;",
        "",
        "internal static partial class MistsMapData",
        "{",
        f"    private const double SmallChestRadius = {small};",
        f"    private const double MediumChestRadius = {medium};",
        "",
        "    private static readonly Dictionary<string, (double X, double Z, bool Medium)[]> Slots = new(StringComparer.OrdinalIgnoreCase)",
        "    {",
    ]
    for name, slots in sorted(masters.items()):
        spots = ", ".join(f"({number(x)}, {number(z)}, {'true' if medium_slot else 'false'})" for x, z, medium_slot in slots)
        lines.append(f'        ["{name}"] = [{spots}],')
    lines += [
        "    };",
        "",
        "    private static readonly Dictionary<string, DungeonLayout> Dungeons = new(StringComparer.OrdinalIgnoreCase)",
        "    {",
    ]
    for name, (low, high, rooms, chests, exits) in sorted(dungeons.items()):
        room_text = ", ".join(f"({', '.join(number(value) for value in room)})" for room in rooms)
        lines += [
            f'        ["{name}"] = new(({number(low[0])}, {number(low[1])}), ({number(high[0])}, {number(high[1])}),',
            f"            [{room_text}],",
            f"            [{points(chests)}],",
            f"            [{points(exits)}]),",
        ]
    lines += ["    };", "}", ""]
    target = ROOT / "AlbionDataAvalonia" / "Maps" / "MistsMapData.g.cs"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {sum(len(x) for x in masters.values())} camp slots of {len(masters)} Mists layouts and "
          f"{sum(len(x[3]) for x in dungeons.values())} chests of {len(dungeons)} Mists dungeons to {target}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: generate-mists-map-data.py <ao-bin-dumps directory>")
    main(sys.argv[1])
