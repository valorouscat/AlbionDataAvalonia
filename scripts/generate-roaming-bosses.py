#!/usr/bin/env python3
"""Writes AlbionDataAvalonia/Activity/ActivityRoamingBossCatalog.g.cs from the game's mobs.json.

The live map can show the roaming bosses near the character. mobs.json (from https://github.com/ao-data/ao-bin-dumps)
gives each mob a danger state and a type: a roaming boss is a "roaming" mob of type "boss" or "miniboss", such as
T8_MOB_ROAMING_UNDEAD_ARCHER_BOSS or the Mists' roaming minibosses. Rerun after a game patch adds mobs:

    curl -sSLo /tmp/mobs.json https://raw.githubusercontent.com/ao-data/ao-bin-dumps/master/mobs.json
    python3 scripts/generate-roaming-bosses.py /tmp/mobs.json
"""
import json
import sys
from pathlib import Path


def main(source: str) -> None:
    mobs = json.loads(Path(source).read_text(encoding="utf-8"))["Mobs"]["Mob"]
    found = {}
    for mob in mobs:
        name = mob.get("@uniquename", "")
        kind = mob.get("@mobtypecategory")
        if name and mob.get("@dangerstate") == "roaming" and kind in ("boss", "miniboss"):
            found[name] = kind == "miniboss"
    lines = [
        "// <auto-generated>",
        "// Written by scripts/generate-roaming-bosses.py from the game's mobs.json; rerun it rather than editing.",
        "// </auto-generated>",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace AlbionDataAvalonia.Activity;",
        "",
        "internal static partial class ActivityLiveActors",
        "{",
        "    // Each roaming boss, and whether it is a miniboss.",
        "    private static readonly Dictionary<string, bool> RoamingBosses = new(StringComparer.OrdinalIgnoreCase)",
        "    {",
    ]
    lines += [f'        ["{name}"] = {"true" if miniboss else "false"},' for name, miniboss in sorted(found.items())]
    lines += ["    };", "}", ""]
    target = Path(__file__).resolve().parent.parent / "AlbionDataAvalonia" / "Activity" / "ActivityRoamingBossCatalog.g.cs"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(found)} roaming bosses to {target}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "mobs.json")
