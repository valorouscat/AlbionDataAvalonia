#!/usr/bin/env python3
"""Writes AlbionDataAvalonia/Maps/MistsCampSlots.g.cs from the game's Mists template files.

A Mists instance is one of a few fixed master layouts with a handful of slots, each filled with a small or medium
section the game picks when the instance opens: a PvE camp, a resource patch, an exit or plain landscape. Only the camps
hold a loot chest, a little off the slot's centre. AlbionWorld's map features list neither the slots nor the chests, so
the map reads them from miststemplatemetadata.xml (the slots of each master) and the camp templates (how far their chest
stands from the centre), both from https://github.com/ao-data/ao-bin-dumps. Rerun after a game patch changes the Mists:

    git clone --depth 1 --filter=blob:none --sparse https://github.com/ao-data/ao-bin-dumps.git /tmp/ao-bin-dumps
    git -C /tmp/ao-bin-dumps sparse-checkout set --no-cone /miststemplatemetadata.xml '/templates/*/MISTS_[MS]_PVE_*'
    python3 scripts/generate-mists-camp-slots.py /tmp/ao-bin-dumps
"""
import math
import re
import sys
import xml.etree.ElementTree as ElementTree
from pathlib import Path

CHEST = re.compile(r'name="SpawnPoint_LOOTCHEST[^"]*"\s+pos="([^"]+)"')


def chest_radius(dumps: Path, size: str) -> int:
    """The farthest any camp of this size puts its chest from its centre, rounded up to whole metres."""
    farthest = 0.0
    for template in dumps.glob(f"templates/*/MISTS_{size[0]}_PVE_*.template.xml"):
        for match in CHEST.finditer(template.read_text(encoding="utf-8")):
            x, _, z = (float(value) for value in match.group(1).split())
            farthest = max(farthest, math.hypot(x, z))
    if farthest == 0:
        raise SystemExit(f"No {size.lower()} Mists camp templates with a chest under {dumps / 'templates'}")
    return math.ceil(farthest)


def number(value: float) -> str:
    return f"{value:g}"


def main(source: str) -> None:
    dumps = Path(source)
    metadata = ElementTree.parse(dumps / "miststemplatemetadata.xml").getroot()
    masters = {}
    for master in metadata.iter("master"):
        slots = []
        for slot in master.iter("slot"):
            x, _, z = (float(value) for value in slot.get("pos", "").split())
            spot = (round(x, 1), round(z, 1), slot.get("size") == "Medium")
            if spot not in slots:
                slots.append(spot)
        if slots:
            masters[master.get("name")] = slots
    small, medium = chest_radius(dumps, "Small"), chest_radius(dumps, "Medium")
    lines = [
        "// <auto-generated>",
        "// Written by scripts/generate-mists-camp-slots.py from the game's Mists templates; rerun it rather than editing.",
        "// </auto-generated>",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace AlbionDataAvalonia.Maps;",
        "",
        "internal static partial class MistsCampSlots",
        "{",
        f"    private const double SmallChestRadius = {small};",
        f"    private const double MediumChestRadius = {medium};",
        "",
        "    private static readonly Dictionary<string, (double X, double Z, bool Medium)[]> Slots = new(StringComparer.OrdinalIgnoreCase)",
        "    {",
    ]
    for name, slots in sorted(masters.items()):
        spots = ", ".join(f"({number(x)}, {number(z)}, {'true' if medium_slot else 'false'})" for x, z, medium_slot in slots)
        lines.append(f'        ["{name}"] = [{spots}],')
    lines += ["    };", "}", ""]
    target = Path(__file__).resolve().parent.parent / "AlbionDataAvalonia" / "Maps" / "MistsCampSlots.g.cs"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {sum(len(x) for x in masters.values())} camp slots of {len(masters)} Mists layouts to {target}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: generate-mists-camp-slots.py <ao-bin-dumps directory>")
    main(sys.argv[1])
