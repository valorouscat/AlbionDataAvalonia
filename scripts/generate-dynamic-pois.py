#!/usr/bin/env python3
"""Build the live Dynamic POI mob catalog from ao-data/ao-bin-dumps mobs.json.

    curl -fsSLo /tmp/mobs.json https://raw.githubusercontent.com/ao-data/ao-bin-dumps/master/mobs.json
    python3 scripts/generate-dynamic-pois.py /tmp/mobs.json

Use the game's explicit categories, not English display-name guesses. Dungeon entrances
are decoded separately from NewRandomDungeonExit. Ordinary seasonal combat mobs are
included because their role is not always categorized (for example Flying Pumpkin).
"""
import json
import sys
from pathlib import Path


def main(source: str) -> None:
    mobs = json.loads(Path(source).read_text(encoding="utf-8"))["Mobs"]["Mob"]
    found = {}
    for mob in mobs:
        name = mob.get("@uniquename", "")
        category = mob.get("@mobtypecategory")
        kind = {"boss": "Boss", "miniboss": "Miniboss", "chest": "Chest"}.get(category)
        if kind is None and "HALLOWEEN" in name and "_RESOURCE" not in name:
            kind = "EventMob"
        if name and kind:
            found[name] = kind
    lines = [
        "// <auto-generated>",
        "// Written by scripts/generate-dynamic-pois.py from the game's mobs.json; rerun rather than editing.",
        "// </auto-generated>",
        "using AlbionDataAvalonia.Activity.Models;",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace AlbionDataAvalonia.Activity;",
        "",
        "internal static partial class ActivityLiveActors",
        "{",
        "    private static readonly Dictionary<string, ActivityLiveActorKind> DynamicMobs = new(StringComparer.OrdinalIgnoreCase)",
        "    {",
    ]
    lines += [f'        ["{name}"] = ActivityLiveActorKind.{kind},' for name, kind in sorted(found.items())]
    lines += ["    };", "}", ""]
    target = Path(__file__).resolve().parent.parent / "AlbionDataAvalonia/Activity/ActivityDynamicPoiCatalog.g.cs"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(found)} dynamic mob POIs to {target}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "mobs.json")
